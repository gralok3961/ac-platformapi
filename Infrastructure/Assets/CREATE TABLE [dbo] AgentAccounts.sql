CREATE TABLE [dbo].[AgentAccounts] (
    -- Unique identifier for this Agent Account backend record.
    -- This is Hashtrion's internal identifier and is NOT the blockchain address.
    [Id] UNIQUEIDENTIFIER NOT NULL
        CONSTRAINT [DF_AgentAccounts_Id] DEFAULT NEWID(),

    -- The currently linked trusted Hashtrion app installation.
    -- This links the Agent Account to the app installation that registered
    -- or currently controls its setup.
    --
    -- IMPORTANT:
    -- This relationship can change later if the wallet is reinstalled
    -- and the Agent Account is recovered on a new trusted installation.
    [AppInstallationId] UNIQUEIDENTIFIER NOT NULL,
    -- Blockchain chain id.
    -- 1 = XRPL
    [ChainId] INT NOT NULL,
    -- Public blockchain address of the Agent Account.
    --
    -- Example XRPL:
    -- rPQVbUg...
    --
    -- This is PUBLIC account information.
    [PublicAddress] NVARCHAR(150)
    COLLATE Latin1_General_100_BIN2 NOT NULL,
    -- Public identifier for this Agent Account.
    -- Generated by Hashtrion when the Agent Account is first registered.
    --
    -- Format: "agt_" + 26-character Base32 encoded 128-bit random value.
    -- Example: agt_7K2M9Q4X6NP3R8T5VY2WADHCJF
    --
    -- Used by external AI agents and platforms to identify
    -- an Agent Account without exposing its internal database ID.
    --
    -- This identifier is not a credential or signing authority.
    -- It remains stable throughout the Agent Account lifecycle.
    [PublicId] VARCHAR(30)
    COLLATE Latin1_General_100_BIN2 NOT NULL,

    -- Operational state of this Agent Account inside Hashtrion.
    --
    -- 1 = Active
    --     Agent functionality is enabled and may be used normally.
    --
    -- 2 = Suspended
    --     Agent functionality is temporarily disabled.
    --     It can be restored to Active later.
    --
    -- 3 = Revoked
    --     Agent functionality is permanently disabled for this backend record.
    --
    [Status] TINYINT NOT NULL
    CONSTRAINT [DF_AgentAccounts_Status] DEFAULT (1),

    -- Record creation timestamp.
    [DateCreated] DATETIMEOFFSET(7) NOT NULL
        CONSTRAINT [DF_AgentAccounts_DateCreated] DEFAULT SYSDATETIMEOFFSET(),

    -- Last update timestamp.
    -- Updated when installation linkage, status, or other account metadata changes.
    [DateUpdated] DATETIMEOFFSET(7) NULL,

    -- Soft delete timestamp.
    -- Normally Status should be used for operational blocking.
    -- This is mainly for record lifecycle / cleanup.
    [DeletedAt] DATETIMEOFFSET(7) NULL,

    CONSTRAINT [PK_AgentAccounts]
        PRIMARY KEY CLUSTERED ([Id]),

    CONSTRAINT [FK_AgentAccounts_AppInstallations_AppInstallationId]
        FOREIGN KEY ([AppInstallationId])
        REFERENCES [dbo].[AppInstallations] ([Id]),

    CONSTRAINT [CK_AgentAccounts_Status]
    CHECK ([Status] IN (1, 2, 3))
);

-- Prevents the same blockchain Agent Account from being registered
-- more than once within this database.
CREATE UNIQUE INDEX [UX_AgentAccounts_ChainId_PublicAddress]
ON [dbo].[AgentAccounts] (
    [ChainId],
    [PublicAddress]
)
WHERE [DeletedAt] IS NULL;

-- Helps retrieve Agent Accounts belonging to a trusted app installation.
CREATE INDEX [IX_AgentAccounts_AppInstallationId]
ON [dbo].[AgentAccounts] ([AppInstallationId])
WHERE [DeletedAt] IS NULL;

CREATE UNIQUE INDEX [UX_AgentAccounts_PublicId]
ON [dbo].[AgentAccounts] ([PublicId]);